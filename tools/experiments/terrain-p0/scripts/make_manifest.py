r"""Write 03-dataset-manifest.json: SHA256, size, CRS, geotransform, NoData, stats of every P0 dataset.
python make_manifest.py --data D:\work\terrain-p0\data --out docs\terrain\p0\03-dataset-manifest.json"""
import argparse, hashlib, json, os
from osgeo import gdal
gdal.UseExceptions()
DESC = {
 "D0": "synthetic analytic surface truth_geo, WGS84 lon/lat, 0.0001 deg", "D1": "synthetic truth_proj, EPSG:4547 CGCS2000 3-degree GK CM 114E, 10 m",
 "D1_4326": "D1 warped to EPSG:4326 by prewarp.ps1 (bilinear)", "D2": "synthetic truth_d2: NoData hole + missing north strip, basin to about -67 m, 300 m cliff at lon 114.25",
 "D3_a": "west half of D3 (truth_geo), shares lon 114.4 edge with D3_b", "D3_b": "east half of D3", "D4": "large synthetic truth_geo BigTIFF 24000x24000, 0.00005 deg",
 "M": "8000x8000 crop of D4 (gdal_translate -srcwin 0 0 8000 8000)"}
ap = argparse.ArgumentParser(); ap.add_argument("--data", required=True); ap.add_argument("--out", required=True); a = ap.parse_args()
items = []
for f in sorted(os.listdir(a.data)):
    if not f.endswith(".tif"): continue
    p = os.path.join(a.data, f); h = hashlib.sha256()
    with open(p, "rb") as fp:
        for blk in iter(lambda: fp.read(1 << 22), b""): h.update(blk)
    ds = gdal.Open(p); b = ds.GetRasterBand(1); srs = ds.GetSpatialRef()
    st = b.GetStatistics(False, True)
    items.append(dict(id=f[:-4], file=f, sha256=h.hexdigest(), bytes=os.path.getsize(p), width=ds.RasterXSize, height=ds.RasterYSize,
        uncompressedBytes=ds.RasterXSize * ds.RasterYSize * 4, dataType=gdal.GetDataTypeName(b.DataType), blockSize=b.GetBlockSize(),
        epsg=srs.GetAuthorityCode(None) if srs else None, crsName=srs.GetName() if srs else None, geoTransform=ds.GetGeoTransform(),
        noData=b.GetNoDataValue(), stats=dict(min=st[0], max=st[1], mean=st[2], std=st[3]),
        verticalDatum="unspecified (synthetic heights; not 1985 national height datum, not converted to ellipsoid)",
        description=DESC.get(f[:-4], ""), authenticity="synthetic, generated by gen_datasets.py seed 20261014"))
json.dump(dict(generator="tools/experiments/terrain-p0/scripts/gen_datasets.py", gdal=gdal.__version__, datasets=items), open(a.out, "w", encoding="utf-8"), indent=1)
print(len(items), "datasets")

